// PROTOTYPE ONLY. Generates src/data/photoIds.ts from a public fantasy API.
// The resulting headshots are NOT licensed for commercial use (docs/data-sources.md).
// Run where the host is reachable:  node scripts/gen-photo-ids.mjs [topN=150]
import { readFileSync, writeFileSync } from 'node:fs';

const TOP = Number(process.argv[2] ?? 150);
const norm = (s) =>
  s.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/['’`.]/g, '')
    .replace(/\b(jr|sr|ii|iii|iv|v)\b/g, '').replace(/[^a-z0-9]+/g, ' ').trim();

const src = readFileSync(new URL('../src/data/players.ts', import.meta.url), 'utf8');
const ours = [...src.matchAll(/id: "([^"]+)", name: "([^"]+)", team: '([A-Z]+)', position: '([A-Z]+)'/g)]
  .slice(0, TOP)
  .map(([, id, name, team, position]) => ({ id, name, team, position }));

const res = await fetch('https://api.sleeper.app/v1/players/nfl');
if (!res.ok) throw new Error(`Player API returned ${res.status}`);
const theirs = Object.values(await res.json()).filter((p) => p.full_name && ['QB', 'RB', 'WR', 'TE'].includes(p.position));
const byKey = new Map();
for (const p of theirs) {
  const k = `${norm(p.full_name)}|${p.position}`;
  // Prefer the active player on a roster when names collide.
  if (!byKey.has(k) || (p.team && !byKey.get(k).team)) byKey.set(k, p);
}

const out = {};
const missed = [];
for (const p of ours) {
  const hit = byKey.get(`${norm(p.name)}|${p.position}`);
  if (hit) out[p.id] = String(hit.player_id);
  else missed.push(p.name);
}

const header = `/**
 * PROTOTYPE ONLY. NOT LICENSED FOR COMMERCIAL USE. SWAP BEFORE LAUNCH.
 *
 * Maps Coil player ids to ids on a public fantasy CDN so the prototype can
 * show headshots. Those images belong to their rights holders; we have no
 * license to ship them. See docs/data-sources.md ("Player photos").
 *
 * Generated by \`node scripts/gen-photo-ids.mjs\` on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.
 */
`;
const body = Object.entries(out).map(([k, v]) => `  ${k}: '${v}',`).join('\n');
writeFileSync(new URL('../src/data/photoIds.ts', import.meta.url), `${header}export const PHOTO_IDS: Record<string, string> = {\n${body}\n};\n`);
console.log(`Mapped ${Object.keys(out).length} of ${ours.length}.`, missed.length ? `Missed: ${missed.join(', ')}` : '');
